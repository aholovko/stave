// testBuild pins the build selection so no test depends on the host platform.
var testBuild = Build{GOOS: "linux", GOARCH: "amd64"}

// writePkg writes authored fixture sources into a fresh package directory. The sources are string constants rather than
// testdata files, because gofmt walks testdata and several fixtures are deliberately not gofmt-clean.
func writePkg(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func shaOf(src string) string {
	sum := sha256.Sum256([]byte(src))
	return hex.EncodeToString(sum[:])
}

// digestOf recomputes the active-file-set digest from first principles. Rows are in ascending path order, and each is
// serialized as path, NUL, hash-or-status, LF.
func digestOf(rows map[string]string) string {
	names := make([]string, 0, len(rows))
	for name := range rows {
		names = append(names, name)
	}
	sort.Strings(names)
	h := sha256.New()
	for _, name := range names {
		h.Write([]byte(name))
		h.Write([]byte{0})
		h.Write([]byte(rows[name]))
		h.Write([]byte{'\n'})
	}
	return hex.EncodeToString(h.Sum(nil))
}

func fileNamed(t *testing.T, snap *Snapshot, name string) File {
	t.Helper()
	f, ok := snap.File(name)
	if !ok {
		t.Fatalf("snapshot has no file %q", name)
	}
	return f
}

func TestEvidenceCoversEverySiblingButTargetsFollowTheBuild(t *testing.T) {
	files := map[string]string{
		"demo.go":         "package demo\n\nvar count int = 1\n",
		"zz_generated.go": "// Code generated by authored-fixture. DO NOT EDIT.\n\npackage demo\n\nvar Generated = 1\n",
		"tool.go":         "//go:build ignore\n\npackage main\n\nfunc main() {}\n\nvar Ignored = 1\n",
		"demo_windows.go": "package demo\n\nvar Windows = 1\n",
		"other.go":        "package other\n\nvar Other = 1\n",
		"_draft.go":       "package demo\n\nvar Draft = 1\n",
		"demo_test.go":    "package demo\n\nvar TestOnly = 1\n",
		"notes.txt":       "var Text = 1\n",
	}
	snap, err := Take(writePkg(t, files), testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}

	wantRoles := map[string]Role{
		"demo.go":         RoleTarget,
		"other.go":        RoleTarget,
		"zz_generated.go": RoleContextOnly,
		"tool.go":         RoleContextOnly,
		"demo_windows.go": RoleContextOnly,
		"_draft.go":       RoleContextOnly,
	}
	if len(snap.Files) != len(wantRoles) {
		t.Errorf("snapshot has %d files, want %d: %+v", len(snap.Files), len(wantRoles), snap.Files)
	}
	for name, want := range wantRoles {
		f := fileNamed(t, snap, name)
		if f.Role != want {
			t.Errorf("%s: role = %s (%s), want %s", name, f.Role, f.Reason, want)
		}
		if want == RoleContextOnly && f.Reason == "" {
			t.Errorf("%s: a non-target needs a visible reason", name)
		}
	}
	if !fileNamed(t, snap, "zz_generated.go").Generated {
		t.Error("zz_generated.go should be recognised as generated")
	}

	for _, name := range []string{"count", "Generated", "Ignored", "Windows", "Other", "Draft"} {
		if !snap.Context.Declares(name) {
			t.Errorf("evidence is missing the declaration %q", name)
		}
	}
	for _, name := range []string{"TestOnly", "Text"} {
		if snap.Context.Declares(name) {
			t.Errorf("%q lies outside the retained evidence and must not be declared", name)
		}
	}

	rows := map[string]string{}
	for name := range wantRoles {
		rows[name] = shaOf(files[name])
	}
	if want := digestOf(rows); snap.Context.Digest() != want {
		t.Errorf("digest = %s, want %s over every evidence row", snap.Context.Digest(), want)
	}
	if !snap.Context.Complete() {
		t.Errorf("every sibling parsed, so the context is complete; got %v", snap.Incomplete)
	}
}

func TestUnknowableSiblingsMakeTheContextExplicitlyIncomplete(t *testing.T) {
	files := map[string]string{
		"demo.go":   "package demo\n\nvar count int = 1\n",
		"broken.go": "package demo\n\nfunc {\n",
		"big.go":    "package demo\n",
		"locked.go": "package demo\n\nvar Locked = 1\n",
	}
	dir := writePkg(t, files)
	// A sparse file one byte over the limit: the size gate must refuse it before any read, so it carries a status and
	// no hash.
	if err := os.Truncate(filepath.Join(dir, "big.go"), MaxFileBytes+1); err != nil {
		t.Fatal(err)
	}
	wantIncomplete := []string{"big.go: oversized", "broken.go: parse-error"}
	wantRows := map[string]string{
		"demo.go":   shaOf(files["demo.go"]),
		"broken.go": shaOf(files["broken.go"]), // read, so the hash wins over the status
		"big.go":    "STATUS:oversized",
		"locked.go": shaOf(files["locked.go"]),
	}
	// Only an enforced mode 0 locks the file: Windows ignores mode bits, and root reads through any mode.
	lockable := runtime.GOOS != "windows" && os.Geteuid() != 0
	if lockable {
		if err := os.Chmod(filepath.Join(dir, "locked.go"), 0); err != nil {
			t.Fatal(err)
		}
		wantIncomplete = append(wantIncomplete, "locked.go: unreadable")
		wantRows["locked.go"] = "STATUS:unreadable"
	}

	snap, err := Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}

	if snap.Context.Complete() {
		t.Error("an unknowable sibling must make the context incomplete")
	}
	if got := strings.Join(snap.Incomplete, "; "); got != strings.Join(wantIncomplete, "; ") {
		t.Errorf("incomplete = %q, want %q", got, strings.Join(wantIncomplete, "; "))
	}
	if want := digestOf(wantRows); snap.Context.Digest() != want {
		t.Errorf("digest = %s, want %s", snap.Context.Digest(), want)
	}
	if f := fileNamed(t, snap, "demo.go"); f.Role != RoleTarget {
		t.Errorf("demo.go: role = %s (%s), want target", f.Role, f.Reason)
	}
	for _, name := range []string{"broken.go", "big.go"} {
		if f := fileNamed(t, snap, name); f.Role != RoleContextOnly || f.Reason == "" {
			t.Errorf("%s: role = %s, reason %q; want context-only with a reason", name, f.Role, f.Reason)
		}
	}
	if f := fileNamed(t, snap, "big.go"); f.SHA256 != "" || f.Src != nil {
		t.Errorf("big.go was read: sha %q, %d bytes", f.SHA256, len(f.Src))
	}
	if lockable && snap.Context.Declares("Locked") {
		t.Error("an unreadable file declares nothing knowable")
	}
}

func TestSymlinksAreFollowedAndNonRegularEntriesNeverOpened(t *testing.T) {
	const linked = "package demo\n\nvar Linked = 1\n"
	outside := writePkg(t, map[string]string{"real.go": linked})
	dir := writePkg(t, map[string]string{"demo.go": "package demo\n"})
	if err := os.Symlink(filepath.Join(outside, "real.go"), filepath.Join(dir, "linked.go")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	if err := os.Mkdir(filepath.Join(dir, "dir.go"), 0o755); err != nil {
		t.Fatal(err)
	}

	snap, err := Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}
	if f := fileNamed(t, snap, "linked.go"); f.SHA256 != shaOf(linked) || f.Role != RoleTarget {
		t.Errorf("linked.go: sha %s role %s, want the link target's bytes as a target", f.SHA256, f.Role)
	}
	if !snap.Context.Declares("Linked") {
		t.Error("a symlinked sibling still contributes its declarations")
	}
	if _, ok := snap.File("dir.go"); ok {
		t.Error("a directory with a Go file name is not evidence")
	}
	if !snap.Context.Complete() {
		t.Errorf("context should be complete, got %v", snap.Incomplete)
	}

	// A dangling link names a sibling nobody can read: fail closed.
	if err := os.Symlink(filepath.Join(outside, "missing.go"), filepath.Join(dir, "dangling.go")); err != nil {
		t.Fatal(err)
	}
	snap, err = Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(snap.Incomplete, "; "); got != "dangling.go: unreadable" {
		t.Errorf("incomplete = %q, want the dangling link", got)
	}
}

func TestOnlyNarrowsTargetsButNeverEvidence(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"demo.go":      "package demo\n\nvar count int = 1\n",
		"sibling.go":   "package demo\n\nvar Sibling = 1\n",
		"demo_test.go": "package demo\n",
	})
	whole, err := Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}

	snap, err := Take(dir, testBuild, []string{"demo.go", "demo_test.go"})
	if err != nil {
		t.Fatal(err)
	}
	if f := fileNamed(t, snap, "demo.go"); f.Role != RoleTarget {
		t.Errorf("demo.go: role = %s (%s), want target", f.Role, f.Reason)
	}
	if f := fileNamed(t, snap, "sibling.go"); f.Role != RoleContextOnly || f.Reason == "" {
		t.Errorf("sibling.go: role = %s, reason %q; want context-only with a reason", f.Role, f.Reason)
	}
	// A requested test file is reported rather than silently dropped, but it lies outside the retained evidence, so it
	// is never read or hashed.
	if f := fileNamed(t, snap, "demo_test.go"); f.Role != RoleIgnored || f.Reason == "" || f.Src != nil {
		t.Errorf("demo_test.go: role = %s, reason %q, %d bytes; want ignored and unread", f.Role, f.Reason, len(f.Src))
	}
	if snap.Context.Digest() != whole.Context.Digest() || !snap.Context.Declares("Sibling") {
		t.Error("narrowing the targets must not change the evidence")
	}

	if _, err := Take(dir, testBuild, []string{"absent.go"}); err == nil {
		t.Error("a requested file that does not exist must be an error, not an empty result")
	}
}

// Enabling test targets must not change package evidence or its digest.
func TestTestTargetsAreOptInAndNeverEvidence(t *testing.T) {
	files := map[string]string{
		"demo.go":            "package demo\n\nvar count int = 1\n",
		"demo_test.go":       "package demo\n\nvar InsideOnly = 1\n",
		"external_test.go":   "package demo_test\n\nvar OutsideOnly = 1\n",
		"broken_test.go":     "package demo\n\nfunc {\n",
		"linux_only_test.go": "//go:build windows\n\npackage demo\n",
		"zz_gen_test.go":     "// Code generated by authored-fixture. DO NOT EDIT.\n\npackage demo\n",
	}
	dir := writePkg(t, files)
	off, err := Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}
	on := testBuild
	on.TestTargets = true
	snap, err := Take(dir, on, nil)
	if err != nil {
		t.Fatal(err)
	}

	if snap.Context.Digest() != off.Context.Digest() || !snap.Context.Complete() {
		t.Errorf("digest %s (complete %v), want the flag-off %s: test files are never evidence",
			snap.Context.Digest(), snap.Context.Complete(), off.Context.Digest())
	}
	for _, name := range []string{"InsideOnly", "OutsideOnly"} {
		if snap.Context.Declares(name) {
			t.Errorf("%s is declared by a test file and must not enter the context", name)
		}
	}
	for name, want := range map[string]string{"demo_test.go": "demo", "external_test.go": "demo_test"} {
		f := fileNamed(t, snap, name)
		if f.Role != RoleTestTarget || f.Reason != "" || f.Package != want || f.SHA256 != shaOf(files[name]) || string(f.Src) != files[name] {
			t.Errorf("%s = role %s (%q), package %q, sha %s; want a read test target of package %s", name, f.Role, f.Reason, f.Package, f.SHA256, want)
		}
	}
	for name, role := range map[string]Role{"broken_test.go": RoleIgnored, "linux_only_test.go": RoleIgnored, "zz_gen_test.go": RoleIgnored} {
		if f := fileNamed(t, snap, name); f.Role != role || f.Reason == "" {
			t.Errorf("%s = role %s (%q), want %s with a visible reason", name, f.Role, f.Reason, role)
		}
	}
	if f := fileNamed(t, snap, "demo.go"); f.Role != RoleTarget {
		t.Errorf("demo.go role = %s, want target", f.Role)
	}

	// Unrequested test files stay outside the snapshot.
	one, err := Take(dir, on, []string{"external_test.go"})
	if err != nil {
		t.Fatal(err)
	}
	if f := fileNamed(t, one, "external_test.go"); f.Role != RoleTestTarget {
		t.Errorf("external_test.go role = %s (%s), want test-target", f.Role, f.Reason)
	}
	if _, listed := one.File("demo_test.go"); listed {
		t.Error("an unrequested test file must not be listed")
	}
	if one.Context.Digest() != off.Context.Digest() {
		t.Error("narrowing to a test file must not change the evidence")
	}
}

func TestTagsChangeTargetsNotTheDigest(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"demo.go":   "package demo\n",
		"tagged.go": "//go:build special\n\npackage demo\n\nvar Tagged = 1\n",
	})
	plain, err := Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}
	tagged, err := Take(dir, Build{GOOS: "linux", GOARCH: "amd64", Tags: []string{"special"}}, nil)
	if err != nil {
		t.Fatal(err)
	}

	if f := fileNamed(t, plain, "tagged.go"); f.Role != RoleContextOnly {
		t.Errorf("without the tag: role = %s, want context-only", f.Role)
	}
	if f := fileNamed(t, tagged, "tagged.go"); f.Role != RoleTarget {
		t.Errorf("with the tag: role = %s (%s), want target", f.Role, f.Reason)
	}
	if plain.Context.Digest() != tagged.Context.Digest() {
		t.Error("the build selection must not move the context digest")
	}
}

// build.Context.MatchFile does not apply the cgo rule that build.Import applies, so a file importing "C" is excluded
// from the targets here when the build selection disables cgo. It stays evidence.
func TestACgoFileIsATargetOnlyWhenTheBuildEnablesCgo(t *testing.T) {
	// Go's build reader unquotes the import path before comparing it to C, so every spelling of the literal is the cgo
	// import.
	for name, spelling := range map[string]string{
		"ordinary": `import "C"`,
		"raw":      "import `C`",
		"escaped":  `import "\x43"`,
	} {
		t.Run(name, func(t *testing.T) {
			files := map[string]string{
				"demo.go":   "package demo\n",
				"native.go": "package demo\n\n" + spelling + "\n\nvar Native int = 1\n",
			}
			dir := writePkg(t, files)

			without, err := Take(dir, Build{GOOS: "linux", GOARCH: "amd64", Cgo: false}, nil)
			if err != nil {
				t.Fatal(err)
			}
			if f := fileNamed(t, without, "native.go"); f.Role != RoleContextOnly || !strings.Contains(f.Reason, "cgo") {
				t.Errorf("cgo disabled: role = %s, reason %q; want context-only because cgo is disabled", f.Role, f.Reason)
			}
			if !without.Context.Declares("Native") || !without.Context.Complete() {
				t.Error("cgo disabled: the file must remain sibling evidence")
			}

			with, err := Take(dir, Build{GOOS: "linux", GOARCH: "amd64", Cgo: true}, nil)
			if err != nil {
				t.Fatal(err)
			}
			if f := fileNamed(t, with, "native.go"); f.Role != RoleTarget {
				t.Errorf("cgo enabled: role = %s (%s), want target", f.Role, f.Reason)
			}
			if with.Context.Digest() != without.Context.Digest() {
				t.Error("the cgo selection must not move the context digest")
			}
		})
	}
}

