func TestTakeBindsOneSavedFileAsEvidenceAndTarget(t *testing.T) {
	const src = "package demo\n\nvar count int = 1\n"
	dir := writePkg(t, map[string]string{"demo.go": src})

	snap, err := Take(dir, testBuild, nil)
	if err != nil {
		t.Fatal(err)
	}

	if !filepath.IsAbs(snap.Dir) {
		t.Errorf("dir %q is not absolute", snap.Dir)
	}
	f := fileNamed(t, snap, "demo.go")
	if f.SHA256 != shaOf(src) || string(f.Src) != src {
		t.Errorf("file does not bind the read bytes: sha %s, src %q", f.SHA256, f.Src)
	}
	if f.Role != RoleTarget || f.Package != "demo" {
		t.Errorf("role/package = %s/%s, want target/demo", f.Role, f.Package)
	}
	if f.Path != filepath.Join(snap.Dir, "demo.go") {
		t.Errorf("path = %q", f.Path)
	}
	if !snap.Context.Complete() || len(snap.Incomplete) != 0 {
		t.Errorf("context should be complete, got incomplete %v", snap.Incomplete)
	}
	if want := digestOf(map[string]string{"demo.go": shaOf(src)}); snap.Context.Digest() != want {
		t.Errorf("digest = %s, want %s", snap.Context.Digest(), want)
	}
	if !snap.Context.Declares("count") {
		t.Error("the context should carry the file's package-block declarations")
	}
}

// Changing GOARCH does not refresh build.Default.ToolTags, so cross-architecture selection needs its own tags.
func TestFeatureTagsFollowTheSelectedArchitectureNotTheHost(t *testing.T) {
	// Use the toolchain defaults (GOAMD64=v1, GOARM64=v8.0), whatever the shell says.
	t.Setenv("GOAMD64", "")
	t.Setenv("GOARM64", "")
	files := map[string]string{
		"arm.go":  "//go:build arm64.v8.0\n\npackage demo\n\nvar FromArm = 1\n",
		"x86.go":  "//go:build amd64.v1\n\npackage demo\n\nvar FromX86 = 1\n",
		"base.go": "package demo\n",
	}
	dir := writePkg(t, files)
	rows := map[string]string{}
	for name, src := range files {
		rows[name] = shaOf(src)
	}
	wantDigest := digestOf(rows)

	for goarch, want := range map[string]map[string]Role{
		"amd64": {"x86.go": RoleTarget, "arm.go": RoleContextOnly, "base.go": RoleTarget},
		"arm64": {"arm.go": RoleTarget, "x86.go": RoleContextOnly, "base.go": RoleTarget},
		"s390x": {"arm.go": RoleContextOnly, "x86.go": RoleContextOnly, "base.go": RoleTarget}, // no feature tags
	} {
		t.Run(goarch, func(t *testing.T) {
			snap, err := Take(dir, Build{GOOS: "linux", GOARCH: goarch}, nil)
			if err != nil {
				t.Fatal(err)
			}
			for name, role := range want {
				f := fileNamed(t, snap, name)
				if f.Role != role {
					t.Errorf("%s: role = %s (%q), want %s", name, f.Role, f.Reason, role)
				}
				if role == RoleContextOnly && !strings.Contains(f.Reason, "build selection") {
					t.Errorf("%s: reason = %q, want the build selection named", name, f.Reason)
				}
			}
			if snap.Context.Digest() != wantDigest || !snap.Context.Declares("FromArm") || !snap.Context.Declares("FromX86") {
				t.Error("the selected architecture must not change the evidence")
			}
		})
	}
}

func TestAFeatureLevelActivatesEveryLowerLevelOfTheSelectedArchitecture(t *testing.T) {
	for _, tc := range []struct {
		goarch, env, level, invalid string
		files                       map[string]string
		want                        map[string]Role
	}{
		{
			goarch: "amd64", env: "GOAMD64", level: "v3", invalid: "v5",
			files: map[string]string{
				"v1.go":  "//go:build amd64.v1\n\npackage demo\n",
				"v2.go":  "//go:build amd64.v2\n\npackage demo\n",
				"v3.go":  "//go:build amd64.v3\n\npackage demo\n",
				"v4.go":  "//go:build amd64.v4\n\npackage demo\n",
				"not.go": "//go:build !amd64.v3\n\npackage demo\n",
			},
			want: map[string]Role{"v1.go": RoleTarget, "v2.go": RoleTarget, "v3.go": RoleTarget, "v4.go": RoleContextOnly, "not.go": RoleContextOnly},
		},
		{
			goarch: "arm64", env: "GOARM64", level: "v9.1", invalid: "v7.0",
			files: map[string]string{
				"v90.go": "//go:build arm64.v9.0\n\npackage demo\n",
				"v91.go": "//go:build arm64.v9.1\n\npackage demo\n",
				"v92.go": "//go:build arm64.v9.2\n\npackage demo\n",
				"v86.go": "//go:build arm64.v8.6\n\npackage demo\n",
				"v87.go": "//go:build arm64.v8.7\n\npackage demo\n",
			},
			want: map[string]Role{"v90.go": RoleTarget, "v91.go": RoleTarget, "v92.go": RoleContextOnly, "v86.go": RoleTarget, "v87.go": RoleContextOnly},
		},
	} {
		t.Run(tc.goarch, func(t *testing.T) {
			if runtime.GOARCH == tc.goarch {
				t.Skip("the host architecture keeps the toolchain's own tags, fixed at process start")
			}
			t.Setenv(tc.env, tc.level)
			dir := writePkg(t, tc.files)
			snap, err := Take(dir, Build{GOOS: "linux", GOARCH: tc.goarch}, nil)
			if err != nil {
				t.Fatal(err)
			}
			for name, role := range tc.want {
				if f := fileNamed(t, snap, name); f.Role != role {
					t.Errorf("%s=%s: %s role = %s (%q), want %s", tc.env, tc.level, name, f.Role, f.Reason, role)
				}
			}

			t.Setenv(tc.env, tc.invalid)
			if _, err := Take(dir, Build{GOOS: "linux", GOARCH: tc.goarch}, nil); err == nil || !strings.Contains(err.Error(), tc.env) {
				t.Errorf("%s=%s: err = %v, want the invalid setting named", tc.env, tc.invalid, err)
			}
		})
	}
}

// Compare the defaults copied from Go 1.26.5 with the host toolchain so upgrades cannot silently change file selection.
func TestTheHostArchitectureKeepsTheToolchainsOwnTags(t *testing.T) {
	host := build.Default.GOARCH
	var hostTags []string
	for _, tag := range build.Default.ToolTags {
		if strings.HasPrefix(tag, host+".") {
			hostTags = append(hostTags, tag)
		}
	}
	t.Logf("host %s/%s tool tags %q", build.Default.GOOS, host, build.Default.ToolTags)
	if got, err := archFeatureTags(host); err != nil || strings.Join(got, " ") != strings.Join(hostTags, " ") {
		t.Errorf("archFeatureTags(%s) = %q, %v; want build.Default's own %q", host, got, err, hostTags)
	}

	files := map[string]string{"plain.go": "package demo\n"}
	want := map[string]Role{"plain.go": RoleTarget}
	for i, tag := range hostTags {
		name := fmt.Sprintf("feature%d.go", i)
		files[name] = "//go:build " + tag + "\n\npackage demo\n"
		want[name] = RoleTarget
		files["not_"+name] = "//go:build !" + tag + "\n\npackage demo\n"
		want["not_"+name] = RoleContextOnly
	}
	dir := writePkg(t, files)
	for _, goos := range []string{build.Default.GOOS, "linux", "windows"} {
		snap, err := Take(dir, Build{GOOS: goos, GOARCH: host}, nil)
		if err != nil {
			t.Fatal(err)
		}
		for name, role := range want {
			if f := fileNamed(t, snap, name); f.Role != role {
				t.Errorf("%s/%s: %s role = %s (%q), want %s", goos, host, name, f.Role, f.Reason, role)
			}
		}
	}
}

