func certRow(t *testing.T, c *Certificate, path string) RowSummary {
	t.Helper()
	for _, r := range c.Summary().Rows {
		if r.Path == path {
			return r
		}
	}
	t.Fatalf("certificate has no row %q", path)
	return RowSummary{}
}

func TestCertificateVerifiedConflictSurvivesIncompleteness(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"target.go": "package demo\n\nfunc f() error { return nil }\n",
		"decl.go":   "package demo\n\nvar errors = 1\n",
		"broken.go": "package demo\n\nfunc {\n",
	})
	c, err := Certify(filepath.Join(dir, "target.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !c.Verified() {
		t.Fatal("an authoritative certificate is verified")
	}
	if conflicts, complete := c.Evidence("errors"); complete || !reflect.DeepEqual(conflicts, []string{"decl.go"}) {
		t.Errorf("errors evidence = %v complete %v, want [decl.go] incomplete", conflicts, complete)
	}
	if conflicts, complete := c.Evidence("fmt"); complete || len(conflicts) != 0 {
		t.Errorf("fmt evidence = %v complete %v, want none incomplete", conflicts, complete)
	}
	if r := certRow(t, c, "broken.go"); r.Status != StatusParseError || r.SHA256 != shaOf("package demo\n\nfunc {\n") ||
		r.Verified || len(r.TopDecls) != 0 {
		t.Errorf("parse-error row = %+v, want its real SHA, unverified and no declarations", r)
	}
}

func TestCertificateDigestMatchesTakeForUntamperedRows(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"target.go": "package demo\n",
		"gen.go":    "// Code generated by fixture. DO NOT EDIT.\n\npackage demo\n\nvar G = 1\n",
		"ex.go":     "//go:build ignore\n\npackage main\n\nfunc main() {}\n",
	})
	snap, err := Take(dir, Build{}, nil)
	if err != nil {
		t.Fatal(err)
	}
	c, err := certify(snap, "target.go")
	if err != nil {
		t.Fatal(err)
	}
	s := c.Summary()
	if s.FileSetDigest != snap.Context.Digest() || !s.Complete {
		t.Errorf("digest %s complete %v, want Take's %s and complete", s.FileSetDigest, s.Complete, snap.Context.Digest())
	}
	if s.Listing.Kind != "directory" || s.Listing.Dir != snap.Dir || s.Target != "target.go" {
		t.Errorf("provenance = %+v target %q", s.Listing, s.Target)
	}
	if r := certRow(t, c, "gen.go"); !r.Verified || !reflect.DeepEqual(r.TopDecls, []string{"G"}) {
		t.Errorf("generated row = %+v, want verified with recomputed declarations", r)
	}
	if r := certRow(t, c, "ex.go"); !r.Verified || !reflect.DeepEqual(r.TopDecls, []string{"main"}) {
		t.Errorf("build-excluded row = %+v, want verified with its declarations", r)
	}
}

func TestCertificateRecomputesAndIgnoresSuppliedEvidence(t *testing.T) {
	const sibling = "package demo\n\nvar fmt = 1\n"
	dir := writePkg(t, map[string]string{
		"target.go":  "package demo\n",
		"sibling.go": sibling,
		"broken.go":  "package demo\n\nfunc {\n",
		"x_test.go":  "package demo\n",
	})
	snap, err := Take(dir, Build{}, []string{"x_test.go"})
	if err != nil {
		t.Fatal(err)
	}
	// Forge the supplied context: complete, and a declaration of errors.
	forged, err := instance.NewPackageContext([]instance.Row{{Path: "broken.go", SHA: shaOf("x"),
		TopDecls: []string{"errors"}}}, true)
	if err != nil {
		t.Fatal(err)
	}
	snap.Context, snap.Incomplete = forged, nil
	// Tamper with the sibling's captured bytes after its SHA was recorded.
	for i := range snap.Files {
		if snap.Files[i].Name == "sibling.go" {
			snap.Files[i].Src = []byte("package demo\n\nvar other = 1\n")
		}
	}
	c, err := certify(snap, "target.go")
	if err != nil {
		t.Fatal(err)
	}
	s := c.Summary()
	if s.Complete {
		t.Error("a forged complete flag is never evidence")
	}
	if conflicts, _ := c.Evidence("errors"); len(conflicts) != 0 {
		t.Errorf("forged declarations produced conflicts %v", conflicts)
	}
	if conflicts, _ := c.Evidence("fmt"); len(conflicts) != 0 {
		t.Errorf("a tampered row is unverified and declares nothing: %v", conflicts)
	}
	r := certRow(t, c, "sibling.go")
	if r.Status != StatusSHAMismatch || r.Verified || r.SHA256 != "" || r.ExpectedSHA256 != shaOf(sibling) ||
		r.ActualSHA256 != shaOf("package demo\n\nvar other = 1\n") || len(r.TopDecls) != 0 {
		t.Errorf("tampered row = %+v", r)
	}
	for _, row := range s.Rows {
		if row.Path == "x_test.go" {
			t.Error("an ignored requested file is not certificate evidence")
		}
	}
	if !certRow(t, c, "target.go").Verified {
		t.Error("the untampered target row stays verified")
	}
}

func TestCertificateTargetIdentity(t *testing.T) {
	const target = "package demo\n\nfunc f() {}\n"
	dir := writePkg(t, map[string]string{"target.go": target, "t_test.go": "package demo\n"})
	if err := os.Mkdir(filepath.Join(dir, "dir.go"), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"missing.go", "t_test.go", "dir.go"} {
		if _, err := Certify(filepath.Join(dir, name)); !errors.Is(err, ErrTargetIdentity) {
			t.Errorf("%s: err = %v, want ErrTargetIdentity", name, err)
		}
	}
	c, err := Certify(filepath.Join(dir, "target.go"))
	if err != nil {
		t.Fatal(err)
	}
	if err := c.CheckTarget([]byte(target)); err != nil {
		t.Errorf("captured bytes: %v", err)
	}
	if err := c.CheckTarget([]byte(target + "\n")); !errors.Is(err, ErrTargetIdentity) {
		t.Errorf("changed bytes: err = %v, want ErrTargetIdentity", err)
	}

	snap, err := Take(dir, Build{}, nil)
	if err != nil {
		t.Fatal(err)
	}
	for i := range snap.Files {
		if snap.Files[i].Name == "target.go" {
			snap.Files[i].Src = []byte("package demo\n")
		}
	}
	tampered, err := certify(snap, "target.go")
	if err != nil {
		t.Fatal(err)
	}
	if err := tampered.CheckTarget([]byte("package demo\n")); !errors.Is(err, ErrTargetIdentity) {
		t.Errorf("tampered target row: err = %v, want ErrTargetIdentity", err)
	}
}

func TestZeroCertificateMeansUnknownContext(t *testing.T) {
	for _, c := range []*Certificate{nil, {}} {
		if c.Verified() {
			t.Error("nil or zero certificate is not verified")
		}
		if conflicts, complete := c.Evidence("errors"); conflicts != nil || complete {
			t.Errorf("zero evidence = %v %v", conflicts, complete)
		}
		if c.Summary() != nil {
			t.Error("zero certificate has no summary")
		}
		if err := c.CheckTarget(nil); !errors.Is(err, ErrTargetIdentity) {
			t.Errorf("zero certificate binds no target: %v", err)
		}
	}
}

func TestCertificateSummaryIsOutputOnly(t *testing.T) {
	dir := writePkg(t, map[string]string{"target.go": "package demo\n\nvar errors, fmt = 1, 2\n"})
	c, err := Certify(filepath.Join(dir, "target.go"))
	if err != nil {
		t.Fatal(err)
	}
	b, err := json.Marshal(c.Summary())
	if err != nil {
		t.Fatal(err)
	}
	var got map[string]any
	if err := json.Unmarshal(b, &got); err != nil {
		t.Fatal(err)
	}
	for _, key := range []string{"listing", "target", "rows", "complete", "file_set_digest", "conflicts"} {
		if _, ok := got[key]; !ok {
			t.Errorf("summary lacks %q: %s", key, b)
		}
	}
	conflicts := got["conflicts"].(map[string]any)
	if !reflect.DeepEqual(conflicts["errors"], []any{"target.go"}) || !reflect.DeepEqual(conflicts["fmt"], []any{"target.go"}) {
		t.Errorf("target declarations count as package conflicts: %v", conflicts)
	}
}
